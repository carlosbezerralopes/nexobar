#!/usr/bin/env python3
"""Port the local MIT Swift point arrays to C#. No Swift execution or downloads.

Run from any directory. --check exits nonzero when the generated file differs.
"""
import argparse
import ast
import hashlib
import math
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
OUTLINES = ROOT / "Sources/NexoBar/ProviderOutlines.swift"
MARKS = ROOT / "Sources/NexoBar/ProviderMarks.swift"
OUTPUT = ROOT / "windows/widbar/ProviderIconPaths.cs"
EXPECTED = {"claude", "codex", "kiro", "cursor", "grok", "copilot", "opencode", "antigravity", "glm"}
NUMBER = r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?"


def generate():
    source = OUTLINES.read_text(encoding="utf-8")
    marks = MARKS.read_text(encoding="utf-8")
    pairs = re.findall(r"case\s+\.(\w+):\s*loops\s*=\s*ProviderOutlines\.(\w+)", marks)
    mapping = dict(pairs)
    if len(pairs) != 9 or set(mapping) != EXPECTED or mapping.get("codex") != "openai":
        raise ValueError("Expected the nine explicit provider mappings, including Codex → OpenAI")
    arrays = {}
    for match in re.finditer(r"static let (\w+):\s*\[\[CGPoint\]\]\s*=\s*", source):
        start = match.end()
        depth, end = 0, None
        for index in range(start, len(source)):
            depth += (source[index] == "[") - (source[index] == "]")
            if depth == 0:
                end = index + 1
                break
        if end is None:
            raise ValueError("Unclosed array")
        array = source[start:end]
        array = re.sub(rf"CGPoint\(x:\s*({NUMBER}),\s*y:\s*({NUMBER})\)", r"[\1, \2]", array)
        loops = ast.literal_eval(array)
        if not loops or any(len(loop) < 3 for loop in loops):
            raise ValueError("Each provider needs closed polygon loops")
        for loop in loops:
            for point in loop:
                if len(point) != 2 or any(not isinstance(n, (float, int)) or not math.isfinite(n) for n in point):
                    raise ValueError("Nonfinite or invalid point")
        if match[1] in arrays:
            raise ValueError("Duplicate outline")
        arrays[match[1]] = loops
    if set(arrays) != set(mapping.values()):
        raise ValueError("Outline mapping mismatch")
    lines = ["// Generated by windows/scripts/generate-provider-icons.py; do not edit.",
             "// Codenotch vectors: MIT, Copyright (c) 2026 Vinz. See THIRD_PARTY_NOTICES.md.",
             f"// Sources SHA256: {hashlib.sha256(OUTLINES.read_bytes()).hexdigest()} / {hashlib.sha256(MARKS.read_bytes()).hexdigest()}",
             "namespace NexoBar.Widget;", "", "internal readonly record struct IconPoint(double X, double Y);",
             "internal static class ProviderIconPaths", "{",
             "    internal static readonly IReadOnlyDictionary<string, IconPoint[][]> All = new Dictionary<string, IconPoint[][]>(StringComparer.Ordinal)", "    {"]
    for provider in sorted(mapping):
        lines.append(f'        ["{provider}"] = [')
        for loop in arrays[mapping[provider]]:
            lines.append("            [" + ", ".join(f"new({x:g}, {y:g})" for x, y in loop) + "],")
        lines.append("        ],")
    lines += ["    };", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            print("ProviderIconPaths.cs differs; run generate-provider-icons.py", file=sys.stderr)
            return 1
        print("PASS nine provider icons match local Swift arrays and mappings")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print("Generated nine provider icons (raw coordinates and all loops preserved)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
